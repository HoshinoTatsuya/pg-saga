import { SAGA_AGGREGATE_TYPE } from '../constants/saga-aggregate-type.constant';
import type { SagaRemoteCommand } from '../types/saga-remote-command.type';

/**
 * `aggregate_type` команды удалённому участнику (`aggregate_id` — id
 * экземпляра). FIFO outbox по агрегату держит событие, пока не ушло
 * предыдущее того же агрегата, поэтому агрегат — ПАРА «участник, экземпляр»:
 *
 * - по умолчанию участник — шаг: `saga-remote:<номер шага>`. Выполнение и
 *   компенсация шага уходят одному участнику и идут по порядку (возврат не
 *   обгоняет списание, повтор — прежнюю попытку), а команда лежащему участнику
 *   одного шага не держит компенсацию у живого участника другого. Команды
 *   разных шагов порядка через outbox не требуют: следующий шаг уходит только
 *   после ответа на предыдущий, компенсация нижнего — после компенсации
 *   верхнего. Тип события выполнения для этого не годится: у компенсации свой;
 * - свой `aggregateType` команды — участник, названный вызывающим: все команды
 *   экземпляра с этим типом идут одной очередью. Разным участникам — разные
 *   типы, а выполнению и компенсации одного шага — один.
 */
export const sagaRemoteAggregateType = (
  remote: Pick<SagaRemoteCommand, 'aggregateType'>,
  stepIndex: number,
): string => remote.aggregateType ?? `${SAGA_AGGREGATE_TYPE.remote}:${stepIndex}`;
