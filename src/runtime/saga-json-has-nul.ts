/**
 * В тексте JSON есть NUL — экранированный `\u0000`, перед которым ЧЁТНОЕ число
 * обратных косых (ноль тоже): jsonb такой символ не хранит. `\\u0000` в тексте
 * JSON — буквальная строка «\u0000» (обратная косая и пять знаков), её jsonb
 * хранит, и отказ по ней был бы ложным.
 */
export const sagaJsonHasNul = (text: string): boolean => /(?:^|[^\\])(?:\\\\)*\\u0000/.test(text);
