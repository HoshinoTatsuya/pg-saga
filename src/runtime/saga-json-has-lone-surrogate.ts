/**
 * В тексте `JSON.stringify` есть непарная половина суррогатной пары: её
 * stringify экранирует (`\ud83d`), а целую пару пишет как есть — и jsonb такой
 * текст отвергает (22P02) посреди транзакции перехода. Перед экраном — ЧЁТНОЕ
 * число обратных косых: `\\ud83d` — буквальный текст, его jsonb хранит.
 */
export const sagaJsonHasLoneSurrogate = (text: string): boolean =>
  /(?:^|[^\\])(?:\\\\)*\\ud[89a-f][0-9a-f]{2}/i.test(text);
