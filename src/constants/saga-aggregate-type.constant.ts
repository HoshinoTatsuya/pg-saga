import { deepFreeze } from '../deep-freeze';

/**
 * `aggregate_type` сообщений саги в outbox. При FIFO по агрегату (outbox
 * `ordering: aggregate`) событие агрегата не уходит, пока не ушло предыдущее,
 * поэтому агрегат выбран по тому, кого сообщение вправе держать:
 *
 * - `command` (id агрегата — id экземпляра) — немедленные команды исполнителю
 *   саги: их порядок держат блокировка строки и сверка адреса, и держат они
 *   только друг друга;
 * - `deferred` (id — id сообщения) — отложенная команда (пауза повтора): не
 *   созревшая, она держала бы всё, что поставлено после неё;
 * - `timer` (id — id сообщения) — таймер ответа удалённого шага: то же;
 * - `reply` (id — id сообщения) — ответ участника событием outbox;
 * - `remote` — ПРЕФИКС агрегата команд участникам по умолчанию:
 *   `saga-remote:<номер шага>`, id — id экземпляра (`sagaRemoteAggregateType`).
 *   Участник может лежать сутки, и его команда на повторах релея не вправе
 *   держать ни команды самой саги, ни команды ДРУГИМ участникам того же
 *   экземпляра. Между собой команды одного шага идут по порядку: компенсация
 *   не обгоняет выполнение.
 */
export const SAGA_AGGREGATE_TYPE = {
  command: 'saga',
  deferred: 'saga-deferred',
  timer: 'saga-timer',
  reply: 'saga-reply',
  remote: 'saga-remote',
} as const;

deepFreeze(SAGA_AGGREGATE_TYPE);
