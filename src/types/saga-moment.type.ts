/**
 * Время перехода в двух смыслах. `at` — отметка (`updated_at`, журнал,
 * `finished_at`, длительности): часы ПОСЛЕ блокировки строки и не раньше
 * последнего сдвига экземпляра (`sagaTimeAfter`), чтобы отстающие часы реплики
 * не уводили её назад. `own` — свои часы процесса: от них считаются СРОКИ
 * (создание и доставка команды, пауза повтора, таймер ответа, `wake_at`). Зажим
 * в сроках переносил бы часы реплики, ушедшей вперёд, в команды верной: те
 * ждали бы, пока реальное время догонит чужие часы.
 */
export interface SagaMoment {
  readonly at: Date;
  readonly own: Date;
}
