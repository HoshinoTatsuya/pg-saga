/** Команда удалённому участнику: событие outbox, которое доставит релей. */
export interface SagaRemoteCommand {
  /** Тип события outbox — по нему порт доставки выбирает участника. */
  readonly eventType: string;
  /** Данные команды (JSON); участник получит их в `data` разобранной команды. */
  readonly payload: unknown;
  /**
   * `aggregate_type` события — участник в FIFO outbox по агрегату (`aggregate_id`
   * — id экземпляра). По умолчанию `saga-remote:<номер шага>`: команды одного
   * шага идут по порядку и не держат команды другим участникам. Свой тип — одна
   * очередь на все команды экземпляра с этим типом: выполнению и компенсации
   * шага — один тип, разным участникам — разные; не `saga` (агрегат команд
   * самой саги — их держала бы команда лежащему участнику).
   */
  readonly aggregateType?: string;
  /** Заголовки события (только с опцией `headers` у outbox). */
  readonly headers?: Readonly<Record<string, string>>;
}
